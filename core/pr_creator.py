"""Pull request creation from applied patches.

Uses a real `git` clone in a temporary directory, so the full diff/commit/push
flow is done against the actual repo rather than the GitHub contents API.
"""

import os
import subprocess
import tempfile
import time

from github import Github

import config

github = __import__("github")


def _run(cmd: list[str], cwd: str | None = None) -> subprocess.CompletedProcess:
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(
            f"command failed ({result.returncode}): {' '.join(cmd)}\n"
            f"stdout: {result.stdout}\nstderr: {result.stderr}"
        )
    return result


def apply_patch_and_create_pr(
    repo_name: str,
    file_path: str,
    patched_content: str,
    ref: str = "main",
) -> str:
    """Clone the repo, checkout a new branch, apply the diff, push, open a PR.

    Args:
        repo_name: 'owner/repo' on GitHub.
        file_path: the file the diff targets (used for the commit message).
        patched_content: a raw unified diff, as produced by core.analyzer.
        ref: the base branch to open the PR against.
    Returns:
        The URL of the opened pull request.
    """
    if not patched_content.strip():
        raise RuntimeError("Refusing to create a PR from an empty diff")

    with tempfile.TemporaryDirectory(prefix="patch-pr-") as tmp:
        subprocess.run(
            ["git", "clone", "--quiet", "--branch", ref, "--depth", "1",
             f"https://x-access-token:{config.GITHUB_TOKEN}@github.com/{repo_name}.git",
             tmp],
            capture_output=True, text=True, check=True,
        )

        branch = f"patch/fix-{time.strftime('%Y%m%d-%H%M%S')}"
        _run(["git", "checkout", "-b", branch], cwd=tmp)

        with tempfile.NamedTemporaryFile(
            mode="w", suffix=".diff", delete=False
        ) as diff_file:
            diff_file.write(patched_content)
            diff_path = diff_file.name

        try:
            _run(["git", "apply", "--whitespace=nowarn", diff_path], cwd=tmp)
        finally:
            os.unlink(diff_path)

        _run(["git", "add", "-A"], cwd=tmp)
        _run(
            ["git", "-c", "user.name=Patch Bot", "-c", "user.email=patch@bot.local",
             "commit", "-m", f"Fix '{file_path}' (automated patch)"],
            cwd=tmp,
        )
        _run(
            ["git", "push", "--quiet", f"https://x-access-token:{config.GITHUB_TOKEN}@github.com/{repo_name}.git",
             f"{branch}:{branch}"],
            cwd=tmp,
        )

    # Instantiating the client lazily here rather than at module import keeps
    # this import cheap for pure pre-config warm-up paths that never reach PR
    # creation.
    gh = Github(config.GITHUB_TOKEN)
    repo = gh.get_repo(repo_name)
    pr = repo.create_pull(
        title=f"Patch bot: fix '{file_path}'",
        body=(
            f"Automated fix proposal for `{file_path}`,\n"
            f"generated by the Patch pipeline from an issue description."
        ),
        head=branch,
        base=ref,
    )
    return pr.html_url
